#!/usr/bin/env python3
"""The module order check: FS-UAE's own modules may only depend on modules below them.

Usage: od-fs/build/module_order.py

The order is fsapp -> fsgui -> fsemu -> the top (everything Amiga-specific). A module may use any
module below it, on its C/C++ side (#include) and its Python side (import) alike; see
od-fs/Docs/Development/Modules.md.

The check reads the #includes of every file in the module directories (od-fs/fs, counted as
part of fsapp for now, od-fs/fsapp, od-fs/fsemu and od-fs/fsuae, the top; fsgui has no
C side) and the imports of every Python package in od-fs/Python, and reports each dependency on a
module above the file's own. Comments are ignored; imports inside functions count.

The check fails on any such dependency, and on a Python import of a module it does not know (a
new C extension module: add it to EXTENSION_MODULES).

Only the Python standard library is used.
"""

import argparse
import ast
import re
import sys
from dataclasses import dataclass
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parents[2]

TOP = "top"

# The modules in the order, lowest first. A module may depend on its own and lower modules.
ORDER = ["fsapp", "fsgui", "fsemu", TOP]
ORDER_TEXT = " -> ".join(ORDER)

# The module directories (relative to the project directory) and their modules.
MODULE_DIRS = {
    # The fs modules count as part of fsapp while code moves there from fsapp (Modules.md). When no
    # fs file includes an fsapp header, fs gets its own place in ORDER, below fsapp.
    "od-fs/fs": "fsapp",
    "od-fs/fsapp": "fsapp",
    # fsgui has no C side (native code it needs goes into fsapp), but a file here would be fsgui's.
    "od-fs/fsgui": "fsgui",
    "od-fs/fsemu": "fsemu",
    "od-fs/fsuae": TOP,
}

# Directories whose headers are outside the order (third-party code).
OUTSIDE_DIRS = ["od-fs/3rdparty"]

# The include path of the build (Makefile.am's -I options for the source tree, in their order),
# where a header that is not next to the including file is looked for. A header found nowhere
# here is a system, SDL, GLib or Python header, or generated by the build: outside the order.
INCLUDE_DIRS = [
    "od-fs/fsapp",
    "od-fs/fsuae",
    "od-fs/unix",
    "include",
    "jit",
    "od-fs",
    "od-fs/include",
    "od-fs/fsemu",
]

# The Python packages in od-fs/Python and their modules (None: third-party, outside the order).
PYTHON_DIR = "od-fs/Python"
PYTHON_PACKAGES: dict[str, str | None] = {
    "fsapp": "fsapp",
    "fsgui": "fsgui",
    "fsemu": "fsemu",
    "fsuae": TOP,
    "uae": TOP,
    "app": TOP,
    "sdl3": None,
    "lhafile": None,
}

# The C extension modules that FS-UAE registers with Python, and their modules (None: third-party).
# Add a new extension module here: an import of one the check does not know is an error.
EXTENSION_MODULES: dict[str, str | None] = {
    "_fsapp": "fsapp",
    "_fsapp_channel": "fsapp",
    "_fsapp_surface": "fsapp",
    "_fsapp_font": "fsapp",
    "_fsapp_image": "fsapp",
    "fsapp_events": "fsapp",
    "_fsemu_input": "fsemu",
    "_fsemu_inputport": "fsemu",
    "fsemu_c": "fsemu",
    "fsemu_inputdevice": "fsemu",
    "_fsuae_main": TOP,
    # lhafile's decompressor, built from od-fs/3rdparty/lhafile.
    "lzhlib": None,
}

# Modules that are neither packages nor extension modules, and outside the order.
STANDARD_MODULES = set(sys.stdlib_module_names) | {"__main__"}

C_SUFFIXES = {".c", ".cc", ".cpp", ".h", ".hpp", ".m", ".mm"}

INCLUDE_PATTERN = re.compile(r'^[ \t]*#[ \t]*include[ \t]*([<"])([^>"\n]+)[>"]', re.MULTILINE)


@dataclass(frozen=True)
class Violation:
    path: str  # the file, relative to the project directory
    line: int
    dependency: str  # the header as included, or the imported module
    module: str  # the file's module
    dependency_module: str

    @property
    def rule(self) -> str:
        return (
            f"{self.module} may not depend on {self.dependency_module}, which is above it "
            f"(the order is {ORDER_TEXT})"
        )

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.dependency} ({self.dependency_module}): {self.rule}"


def is_below(directory: Path, parent: Path) -> bool:
    return directory == parent or parent in directory.parents


def module_of_path(project_dir: Path, path: Path) -> str | None:
    """The module a file belongs to: its module directory's, the top for the rest of the project,
    or None for third-party code and files outside the project."""
    path = path.resolve()
    for directory, module in MODULE_DIRS.items():
        if is_below(path, project_dir / directory):
            return module
    for directory in OUTSIDE_DIRS:
        if is_below(path, project_dir / directory):
            return None
    if is_below(path, project_dir):
        return TOP
    return None


def without_comments(text: str) -> str:
    """The C/C++ source text with its comments replaced by spaces (line breaks kept, so that the
    line numbers stay the same). String and character literals are skipped, so that a // in a
    string does not start a comment."""
    result: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            end = text.find("\n", i)
            end = n if end == -1 else end
            result.append(" " * (end - i))
            i = end
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            end = n if end == -1 else end + 2
            result.append("".join(ch if ch == "\n" else " " for ch in text[i:end]))
            i = end
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            end = min(j + 1, n)
            result.append(text[i:end])
            i = end
        else:
            result.append(c)
            i += 1
    return "".join(result)


def resolve_include(project_dir: Path, including: Path, kind: str, name: str) -> Path | None:
    candidates: list[Path] = []
    if kind == '"':
        candidates.append(including.parent / name)
    candidates.extend(project_dir / directory / name for directory in INCLUDE_DIRS)
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


def upward_violation(
    path: str, line: int, dependency: str, module: str, dependency_module: str | None
) -> Violation | None:
    """The violation if module depends on dependency_module, which is above it (None for a
    dependency outside the order)."""
    if dependency_module is None or ORDER.index(dependency_module) <= ORDER.index(module):
        return None
    return Violation(
        path=path,
        line=line,
        dependency=dependency,
        module=module,
        dependency_module=dependency_module,
    )


def c_violations(project_dir: Path) -> list[Violation]:
    violations: list[Violation] = []
    for directory, module in MODULE_DIRS.items():
        for path in sorted((project_dir / directory).rglob("*")):
            if path.suffix not in C_SUFFIXES or not path.is_file():
                continue
            text = without_comments(path.read_text(errors="replace"))
            for match in INCLUDE_PATTERN.finditer(text):
                kind, name = match.group(1), match.group(2).strip()
                header = resolve_include(project_dir, path, kind, name)
                dependency_module = None if header is None else module_of_path(project_dir, header)
                violation = upward_violation(
                    path.relative_to(project_dir).as_posix(),
                    text.count("\n", 0, match.start()) + 1,
                    name,
                    module,
                    dependency_module,
                )
                if violation:
                    violations.append(violation)
    return violations


def python_imports(tree: ast.AST) -> list[tuple[int, str]]:
    """The absolute imports in a module (anywhere in it, also inside functions), as line numbers and
    module names: the imported module for import, and the module imported from for from-imports."""
    imports: list[tuple[int, str]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imports.extend((node.lineno, alias.name) for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            imports.append((node.lineno, node.module))
    return sorted(imports)


def python_violations(project_dir: Path) -> tuple[list[Violation], list[str]]:
    """The violations in the Python packages, and errors for packages and imported modules that the
    check does not know."""
    violations: list[Violation] = []
    errors: list[str] = []
    python_dir = project_dir / PYTHON_DIR
    if not python_dir.is_dir():
        return violations, errors
    for package_dir in sorted(python_dir.iterdir()):
        if not package_dir.is_dir() or package_dir.name[0] in "_.":
            continue
        if package_dir.name not in PYTHON_PACKAGES:
            errors.append(
                f"{PYTHON_DIR}/{package_dir.name}: a Python package that the check does not know; "
                "add it to PYTHON_PACKAGES in od-fs/build/module_order.py with its module"
            )
            continue
        module = PYTHON_PACKAGES[package_dir.name]
        if module is None:
            continue
        for path in sorted(package_dir.rglob("*.py")):
            relative = path.relative_to(project_dir).as_posix()
            tree = ast.parse(path.read_bytes(), filename=relative)
            for line, name in python_imports(tree):
                top_name = name.split(".")[0]
                if top_name in PYTHON_PACKAGES:
                    dependency_module = PYTHON_PACKAGES[top_name]
                elif top_name in EXTENSION_MODULES:
                    dependency_module = EXTENSION_MODULES[top_name]
                elif top_name in STANDARD_MODULES:
                    dependency_module = None
                else:
                    errors.append(
                        f"{relative}:{line}: {name}: a module that the check does not know (not a "
                        f"package in {PYTHON_DIR} or in the standard library); if it is a C "
                        "extension module, add it to EXTENSION_MODULES in "
                        "od-fs/build/module_order.py with its module"
                    )
                    continue
                violation = upward_violation(relative, line, name, module, dependency_module)
                if violation:
                    violations.append(violation)
    return violations, errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.parse_args()

    violations, errors = python_violations(PROJECT_DIR)
    violations = c_violations(PROJECT_DIR) + violations
    if violations:
        print(f"Dependencies that break the module order ({len(violations)}):")
        for violation in violations:
            print(f"  {violation}")
    for error in errors:
        print(error)
    if violations or errors:
        return 1
    print("The module order check passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
